function GalleryPage({
  property,
  data,
  propertyIndex,
  images,
  galleryPageIndex,
}: {
  property: PdfProperty;
  data: PdfData;
  propertyIndex: number;
  images: string[];
  galleryPageIndex: number;
}) {
  const t =
    dictionary(
      data.language
    );

  const firstPhotoNumber =
    2 +
    galleryPageIndex *
      6;

  const lastPhotoNumber =
    firstPhotoNumber +
    images.length -
    1;

  return (
    <Page
      size="A4"
      style={
        styles.galleryPage
      }
    >
      <View
        style={
          styles.galleryHeader
        }
      >
        <View>
          <Text
            style={
              styles.galleryEyebrow
            }
          >
            {data.language === "id"
              ? `Properti ${propertyIndex + 1} • Galeri`
              : `Property ${propertyIndex + 1} • Gallery`}
          </Text>

          <Text
            style={
              styles.galleryTitle
            }
          >
            {t.gallery}
          </Text>

          <Text
            style={
              styles.galleryPropertyTitle
            }
          >
            {property.title}
          </Text>
        </View>

        <View>
          <Text
            style={
              styles.galleryPhotoLabel
            }
          >
            {t.photos}
          </Text>

          <Text
            style={
              styles.galleryPhotoRange
            }
          >
            {firstPhotoNumber}
            {" – "}
            {lastPhotoNumber}
          </Text>
        </View>
      </View>

      <View
        style={
          styles.galleryGrid
        }
      >
        {images.map(
          (
            image,
            imageIndex
          ) => {
            const isFeature =
              imageIndex === 0;

            const isLast =
              imageIndex ===
              images.length - 1;

            const shouldSpanLast =
              !isFeature &&
              isLast &&
              images.length % 2 ===
                0;

            return (
              <Image
                key={`${property.id}-${galleryPageIndex}-${imageIndex}`}
                src={image}
                style={
                  isFeature
                    ? styles.galleryFeature
                    : shouldSpanLast
                      ? styles.galleryWide
                      : styles.galleryHalf
                }
              />
            );
          }
        )}
      </View>

      <View
        style={styles.footer}
        fixed
      >
        <Text>
          TETAMO • Properti Marketplace
        </Text>

        <Text
          render={({
            pageNumber,
          }) =>
            `${t.page} ${pageNumber}`
          }
        />
      </View>
    </Page>
  );
}

