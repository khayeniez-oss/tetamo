function formatProposalPdfValue(
  value: unknown,
  language: AgentProposalLanguage
) {
  if (
    value === null ||
    value === undefined
  ) {
    return "";
  }

  if (
    typeof value === "number"
  ) {
    return value > 0
      ? String(value)
      : "";
  }

  const raw =
    String(value).trim();

  if (
    !raw ||
    raw === "-" ||
    raw === "0"
  ) {
    return "";
  }

  const key =
    raw
      .toLowerCase()
      .replace(/\s+/g, "_");

  const english:
    Record<string, string> = {
    rumah: "House",
    villa: "Villa",
    apartemen: "Apartment",
    apartment: "Apartment",
    tanah: "Land",
    dijual: "For Sale",
    disewa: "For Rent",
    dijual_disewa:
      "For Sale / Rent",
    tanah_hunian:
      "Residential Land",
    permukiman:
      "Residential",
    fully_furnished:
      "Fully Furnished",
    semi_furnished:
      "Semi Furnished",
    unfurnished:
      "Unfurnished",
  };

  const indonesian:
    Record<string, string> = {
    rumah: "Rumah",
    villa: "Villa",
    apartemen: "Apartemen",
    apartment: "Apartemen",
    tanah: "Tanah",
    dijual: "Dijual",
    disewa: "Disewa",
    dijual_disewa:
      "Dijual / Disewa",
    tanah_hunian:
      "Tanah Hunian",
    permukiman:
      "Permukiman",
    fully_furnished:
      "Fully Furnished",
    semi_furnished:
      "Semi Furnished",
    unfurnished:
      "Tanpa Furnitur",
  };

  const mapped =
    language === "en"
      ? english[key]
      : indonesian[key];

  if (mapped) {
    return mapped;
  }

  return raw
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(
      /\b\w/g,
      (letter) =>
        letter.toUpperCase()
    );
}

function clampProposalPdfText(
  value: string | null | undefined,
  maxLength = 1250
) {
  const clean =
    String(value || "")
      .trim();

  if (
    clean.length <=
    maxLength
  ) {
    return clean;
  }

  return (
    clean.slice(
      0,
      maxLength
    ).trimEnd() +
    "…"
  );
}

function chunkProposalGallery(
  images: string[]
) {
  const galleryImages =
    images.slice(1);

  const chunks:
    string[][] = [];

  for (
    let index = 0;
    index <
    galleryImages.length;
    index += 6
  ) {
    chunks.push(
      galleryImages.slice(
        index,
        index + 6
      )
    );
  }

  return chunks;
}

